const MISSING = '##### #...# #...# #...# #...# #...# #####'

const cache = new Map<string, boolean[][]>()

/** A character's 7 rows of 5 (true: on). A character this font does not have: a hollow box */
export function glyph(char: string): boolean[][] {
  let found = cache.get(char)
  if (!found) {
    const source = G[char] ?? MISSING
    found = source.split(' ').map((row) => [...row].map((c) => c === '#'))
    cache.set(char, found)
  }
  return found
}

/** Whether the font has this character */
export const hasGlyph = (char: string) => char in G

export const FONT_CHARS = Object.keys(G)
